#!/usr/bin/env python3
"""Records track summary (PLAN.md §7): per-problem frontier and stated compute totals.

Reads records/<class>/*.yaml via pipeline/load_records.py and writes
analysis/records_frontier.md. Only raw, as-stated figures are summed; no
cross-hardware normalization is applied here (see the open item in STATUS.md).
All records are unverified until a human checks them.
"""
import sys, collections
sys.path.insert(0, "pipeline")
from load_records import all_records

def num(x):
    try: return float(x)
    except (TypeError, ValueError): return None

rs = [r for r in all_records() if not r["_summary"]]
groups = collections.defaultdict(list)
for r in rs: groups[(r["class"], r["problem"], r.get("challenge") or "")].append(r)

out = ["# Computational records: frontier and stated compute", "",
       f"Generated by analysis/records_frontier.py from {len(rs)} record files (summary files excluded).",
       "Every record is UNVERIFIED (agent-transcribed, source_url given in each file).",
       "Frontier = records that raised the largest instance_size within a (class, problem, challenge) group, in date order.", ""]

out += ["## Stated compute totals by class", "",
        "| class | records | academic | non-academic | with stated core-years | sum core-years | with stated GPU-years | sum GPU-years | no compute stated |",
        "|---|---|---|---|---|---|---|---|---|"]
for cls in ["ecdlp", "lattice", "code", "comparator"]:
    c = [r for r in rs if r["class"] == cls]
    cy = [num(r.get("reported_core_years")) for r in c if num(r.get("reported_core_years"))]
    gy = [num(r.get("gpu_years")) for r in c if num(r.get("gpu_years"))]
    none = sum(1 for r in c if not num(r.get("reported_core_years")) and not num(r.get("gpu_years")))
    out.append(f"| {cls} | {len(c)} | {sum(1 for r in c if r.get('academic'))} | {sum(1 for r in c if r.get('academic') is False)} | "
               f"{len(cy)} | {sum(cy):,.1f} | {len(gy)} | {sum(gy):,.2f} | {none} |")
out += ["", "Sums mix hardware generations (1997 Alpha machine-days through 2026 GPUs) and are only order-of-magnitude.", ""]

for key in sorted(groups):
    g = sorted(groups[key], key=lambda r: str(r.get("date") or ""))
    best, front = None, []
    for r in g:
        s = num(r.get("instance_size"))
        if s is not None and (best is None or s > best): best = s; front.append(r)
    if not front: continue
    cls, prob, ch = key
    out += [f"## {cls} / {prob}" + (f" / {ch}" if ch else ""), "",
            "| date | instance | size | log2 ops | method | structure | compute (as stated) | conf |", "|---|---|---|---|---|---|---|---|"]
    for r in front:
        rc = (r.get("raw_compute") or "").replace("|", "/")[:90]
        out.append(f"| {r.get('date')} | {(r.get('instance') or '')[:50]} | {r.get('instance_size')} {r.get('instance_size_unit') or ''} | "
                   f"{r.get('log2_ops') if r.get('log2_ops') is not None else ''} | {(r.get('method') or '')[:40]} | "
                   f"{'yes' if r.get('structure_exploited') else ''} | {rc} | {r.get('confidence')} |")
    out.append("")
open("analysis/records_frontier.md", "w").write("\n".join(out) + "\n")
print("\n".join(out[:20]))
