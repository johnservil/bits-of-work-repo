#!/usr/bin/env python3
"""Part 2: compare public cryptanalytic effort (author map) with scenario
estimates of classified Five Eyes effort, per assumption class.

Inputs: data/authors/fte_by_year.csv (analysis/author_map.py),
        analysis/classified_scenarios.json (parameters with sources).
Output: analysis/classified_scenarios.txt (stdout).

Public side: calendar person-years per year (research-FTE x career-stage research
fraction), mean over the period in the JSON. Classified side: sum of component
headcounts (low/mid/high) x public-key share (low/mid/high), split across
classes by allocation scenario. Classified staff are counted as full-time; the
public side is already converted to calendar time, so the two are comparable.
"""
import csv, json

P = json.load(open("analysis/classified_scenarios.json"))
CL = ["ECDLP", "Lat(any)", "SD", "Fact/FFDLP", "Isog", "MQ"]
NAMES = {"ECDLP": "ECDLP", "Lat(any)": "Lattices (MLWE+LWE)", "SD": "Syndrome decoding",
         "Fact/FFDLP": "Factoring / FF-DLP", "Isog": "Isogeny", "MQ": "Multivariate"}
R = {int(r["year"]): r for r in csv.DictReader(open("data/authors/fte_by_year.csv"))}
a, b = P["period"]; yrs = range(a, b + 1)
pub_cal = {c: sum(float(R[y][f"{c}_person_years"]) for y in yrs) / len(yrs) for c in CL}
pub_fte = {c: sum(float(R[y][f"{c}_fte_total"]) for y in yrs) / len(yrs) for c in CL}
tot_cal = sum(pub_cal.values()); tot_fte = sum(pub_fte.values())
out = []; pr = out.append

pr(f"CLASSIFIED VS PUBLIC CRYPTANALYTIC EFFORT, {a}-{b} (scenarios; generated by analysis/classified_scenarios.py)\n")
pr("Public effort per year (author map): research-FTE and calendar person-years")
for c in CL: pr(f"  {NAMES[c]:22s} {pub_fte[c]:6.1f} FTE  {pub_cal[c]:6.1f} person-years/yr")
pr(f"  {'all six classes':22s} {tot_fte:6.1f} FTE  {tot_cal:6.1f} person-years/yr\n")

comp = P["components"]
M = {k: sum(v[k] for v in comp.values()) for k in ("low", "mid", "high")}
pr("Classified mathematical cryptology research staff, Five Eyes (FTE)")
for name, v in comp.items(): pr(f"  {name[:62]:62s} {v['low']:5d} {v['mid']:5d} {v['high']:5d}")
pr(f"  {'total':62s} {M['low']:5d} {M['mid']:5d} {M['high']:5d}")
bc = P["budget_crosscheck"]; lo, hi = bc["loaded_cost_per_fte_usd"]
pr(f"  budget cross-check: $119-146M/yr at ${lo//1000}-{hi//1000}k per FTE = {119.3e6/hi:.0f}-{146.4e6/lo:.0f} FTE (NSA math research + IDA, FY2011-13)\n")

f = P["public_key_share"]
pk = {"low": M["low"] * f["low"], "mid": M["mid"] * f["mid"], "high": M["high"] * f["high"]}
pr(f"Share on public-key assumption cryptanalysis: {f['low']:.0%} / {f['mid']:.0%} / {f['high']:.0%}")
pr(f"Classified public-key cryptanalysis (FTE): low {pk['low']:.0f}, mid {pk['mid']:.0f}, high {pk['high']:.0f}")
pr(f"  vs public {tot_cal:.0f} person-years/yr -> ratio {pk['low']/tot_cal:.2f}x / {pk['mid']/tot_cal:.2f}x / {pk['high']/tot_cal:.2f}x\n")

pr("Per class: classified FTE (mid headcount x mid share, range = low..high) and ratio to public calendar effort")
for scen, alloc in P["allocation_scenarios"].items():
    if scen.startswith("_"): continue
    if alloc == "public": alloc = {c: pub_cal[c] / tot_cal for c in CL}
    pr(f"  scenario: {scen}")
    pr(f"    {'class':22s} {'share':>6s} {'classified':>18s} {'public':>7s} {'ratio mid (low-high)':>22s}")
    for c in CL:
        s = alloc[c]
        lo_, mi, hi_ = (pk[k] * s for k in ("low", "mid", "high"))
        pr(f"    {NAMES[c]:22s} {s:6.0%} {mi:6.0f} ({lo_:4.0f}-{hi_:4.0f}) {pub_cal[c]:7.1f} {mi/pub_cal[c]:8.1f}x ({lo_/pub_cal[c]:.1f}-{hi_/pub_cal[c]:.1f})")
    pr("")

pr("Combined scrutiny (public + classified, mid) relative to public alone, by scenario")
for scen, alloc in P["allocation_scenarios"].items():
    if scen.startswith("_"): continue
    if alloc == "public": alloc = {c: pub_cal[c] / tot_cal for c in CL}
    pr(f"  {scen[:45]:45s} " + "  ".join(f"{c}: {(pub_cal[c] + pk['mid'] * alloc[c]) / pub_cal[c]:.1f}x" for c in CL))
print("\n".join(out))
