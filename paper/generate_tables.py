#!/usr/bin/env python3
"""Rebuild white-paper tables from committed study outputs (stdlib only)."""
from pathlib import Path
from decimal import Decimal, ROUND_HALF_UP
import csv, hashlib, json
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'paper/generated'
OUT.mkdir(exist_ok=True)
D = Decimal
COST, HOURS = D(250000), D(2000)
SOURCES = ['analysis/phase1_counts.txt', 'data/authors/fte_by_year.csv',
           'data/export/combined_included.csv', 'data/ai_effort/ai_results.yaml']
classes = [
 ('ECDLP','ECDLP','ECDLP'),
 ('All lattices','ALL LATTICES','Lat(any)'),
 ('MLWE / structured','MLWE_structured','MLWE'),
 ('Plain LWE','LWE_plain','LWE'),
 ('Syndrome decoding','SD_code','SD'),
 ('Factoring / FF-DLP','Factoring_FFDLP','Fact/FFDLP'),
 ('Isogenies','Isogeny','Isog'),
 ('Multivariate','Multivariate','MQ')]
text = (ROOT/SOURCES[0]).read_text()
section = next(s for s in text.split('\n== ') if s.startswith('COMBINED, all sources:'))
counts={}
for _, label, _ in classes:
 line = next(l for l in section.splitlines() if l.startswith(label+' '))
 v = line[len(label):].split()
 counts[label] = dict(papers=D(v[0]), touch=int(v[1]), authors=int(v[2]), eras=list(map(D,v[3:6])))
with (ROOT/SOURCES[1]).open() as f: yearly=list(csv.DictReader(f))
latest = next(r for r in yearly if r['year']=='2026')
def num(v, digits=1):
 value=D(v).quantize(D(1).scaleb(-digits),rounding=ROUND_HALF_UP)
 return f'{value:,.{digits}f}'
def write(name, rows):
 (OUT/name).write_text('% Generated by paper/generate_tables.py; do not edit.\n'+'\n'.join(rows)+'\n')
lit=[]; labor=[]; budget=[]; data=[]
for title,label,key in classes:
 c=counts[label]; h=D(latest[key+'_fte_cumulative']); cal=D(latest[key+'_person_years_cumulative'])
 lit.append(' & '.join([title,num(c['papers']),str(c['touch']),*[num(v) for v in c['eras']]])+r' \\')
 labor.append(' & '.join([title,num(h),num(h*HOURS/1000),num(cal*HOURS/1000)])+r' \\')
 budget.append(' & '.join([title,*[num(h*COST/s/1000000,2) for s in [1,10,100]]])+r' \\')
 data.append(dict(class_name=title,papers=str(c['papers']),research_years=str(h),nominal_hours=str(h*HOURS),adjusted_hours=str(cal*HOURS),budgets={str(s):str(h*COST/s) for s in [1,10,100]}))
write('literature_rows.tex',lit);write('labor_rows.tex',labor);write('budget_rows.tex',budget)
with (OUT/'cumulative.csv').open('w',newline='') as f:
 w=csv.writer(f,lineterminator='\n');w.writerow(['year','ecdlp','lattice','code','factoring'])
 for r in yearly:
  w.writerow([r['year'],*[r[k+'_fte_cumulative'] for k in ['ECDLP','Lat(any)','SD','Fact/FFDLP']]])
PRI={'A':(1,2),'C':(1,2),'F':(1,2),'H':(1,2),'D':(.5,1.5),'E':(2,10),'S':(.5,1)}
def estimate(problem):
 path=f'data/ai_effort/calib/{problem}/labeled_final.jsonl'; SOURCES.append(path)
 rows=[json.loads(l) for l in (ROOT/path).read_text().splitlines()]
 lo=hi=D(0); n=0; flagged=0
 for row in rows:
  l=row.get('label') or row
  if l.get('include') not in ('yes','borderline') or l.get('category') not in PRI: continue
  w=D(str(l.get('weight') or 0))*(D('.5') if l['include']=='borderline' else D(1))
  a,b=map(lambda x:D(str(x)),PRI[l['category']]);lo+=w*a;hi+=w*b;n+=1
  flagged+=int(bool(l.get('ai_assisted')))
 return dict(problem=problem,mid=(lo+hi)/2,lo=lo,hi=hi,items=n,flagged_ai=flagged)
all_est={}
for p in sorted((ROOT/'data/ai_effort/calib').glob('*/labeled_final.jsonl')):
 all_est[p.parent.name]=estimate(p.parent.name)
selected=[('UGC','Unique Games line'),('2to1','2-to-1 Games line'),('hawk','HAWK / module-LIP'),
          ('erdos-1',r'Erd\H{o}s \#1'),('erdos-74',r'Erd\H{o}s \#74'),('erdos-126',r'Erd\H{o}s \#126'),
          ('erdos-548',r'Erd\H{o}s \#548'),('erdos-571',r'Erd\H{o}s \#571')]
rows=[]
for key,title in selected:
 e=all_est[key]
 rows.append(' & '.join([title,num(e['mid']),num(e['mid']*HOURS/1000),f"{num(e['lo'])}--{num(e['hi'])}"])+r' \\')
write('problem_rows.tex',rows)
rows=[]
for key in sorted((k for k in all_est if k.startswith('erdos-')),key=lambda x:int(x[6:])):
 e=all_est[key]
 rows.append(' & '.join([key[6:],num(e['mid']),f"{num(e['lo'])}--{num(e['hi'])}",str(e['items'])])+r' \\')
write('erdos_rows.tex',rows)
export_count=sum(1 for _ in csv.DictReader((ROOT/'data/export/combined_included.csv').open()))
write('snapshot.tex',[r'\newcommand{\ExportRows}{'+f'{export_count:,}'+r'}'])
manifest={'as_of':'2026-10-09','hours_per_research_year':str(HOURS),'usd_per_research_year':str(COST),
 'multipliers':[1,10,100],'classes':data,'problems':all_est,'source_sha256':{p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in SOURCES}}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2,default=str)+'\n')
print(f'Generated 8 class rows, {len(selected)} comparison rows, {len(rows)} Erdos rows; export has {export_count} rows.')
