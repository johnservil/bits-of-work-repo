def main():
    os.makedirs(OUT, exist_ok=True)
    ids = set()
    for r in RECORDS:
        assert r["id"] not in ids, r["id"]
        ids.add(r["id"])
        missing = [k for k in KEYS if k not in r]
        extra = [k for k in r if k not in KEYS]
        assert not missing and not extra, (r["id"], missing, extra)
        assert r["verified"] is False and r["source_url"]
        lines = ["# comparator computational record; generated by records/comparator/_scratch/gen.py"]
        for k in KEYS:
            lines.append("%s: %s" % (k, json.dumps(r[k], ensure_ascii=False)))
        with open(os.path.join(OUT, r["id"] + ".yaml"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    print("wrote", len(RECORDS))


if __name__ == "__main__":
    main()
